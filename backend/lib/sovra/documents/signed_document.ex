defmodule Sovra.Documents.SignedDocument do
  @moduledoc """
  A document signed directly by an issuer, with no holder and no wallet.

  `credential`, the compact JWS, is the only copy of the claims: anything that
  shows them decodes it, so a rendering cannot drift from what was signed.
  `digest` is the value the signature covers.
  """

  use Ecto.Schema
  import Ecto.Changeset

  @primary_key {:id, :binary_id, autogenerate: true}
  @foreign_key_type :binary_id

  @statuses ~w(signed anchored failed revoked)
  @visibilities ~w(public private)

  schema "signed_documents" do
    field :credential, :string
    field :digest, :binary
    field :status, :string, default: "signed"
    field :visibility, :string, default: "private"
    field :status_list_index, :integer
    field :tx_hash, :string
    field :signed_at, :utc_datetime
    field :anchored_at, :utc_datetime
    field :revoked_at, :utc_datetime

    belongs_to :workspace, Sovra.Workspaces.Workspace
    belongs_to :schema, Sovra.Issuer.CredentialSchema

    timestamps(type: :utc_datetime)
  end

  # `id` is supplied by the caller, not autogenerated: it is signed into the
  # payload as `jti` before the row exists.
  @required ~w(id workspace_id schema_id credential digest signed_at)a
  @optional ~w(status visibility status_list_index tx_hash anchored_at revoked_at)a

  def create_changeset(record \\ %__MODULE__{}, attrs) do
    record
    |> cast(attrs, @required ++ @optional)
    |> validate_required(@required)
    |> validate_inclusion(:status, @statuses)
    |> validate_inclusion(:visibility, @visibilities)
    |> unique_constraint([:workspace_id, :digest])
  end

  @doc """
  Status transitions and the chain metadata that comes with them.
  """
  def status_changeset(record, attrs) do
    record
    |> cast(attrs, [:status, :tx_hash, :anchored_at, :revoked_at])
    |> validate_inclusion(:status, @statuses)
  end

  @doc """
  Who may read the document. Not covered by the signature, so it can change
  without invalidating anything.
  """
  def visibility_changeset(record, visibility) do
    record
    |> cast(%{visibility: visibility}, [:visibility])
    |> validate_required([:visibility])
    |> validate_inclusion(:visibility, @visibilities)
  end

  def statuses, do: @statuses
  def visibilities, do: @visibilities
end
