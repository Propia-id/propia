defmodule Sovra.Repo.Migrations.AddMdlCertificates do
  use Ecto.Migration

  @moduledoc """
  The tables behind issuing a real mDL.

  Sovra's own mdoc credentials carry the issuer's address inside a generated
  docType, and a verifier reads it back out to find them. An ISO docType —
  `org.iso.18013.5.1.mDL` — carries no address, so that route disappears and
  trust has to come from a certificate chain instead. These columns are where
  that chain lives.
  """

  def change do
    # A trust anchor. Its existence *is* the admission decision: only a platform
    # admin can create one, and our verifiers accept a chain exactly when it
    # ends at a row in this table. There is deliberately no status column —
    # a second flag would be a second decision that could disagree with the
    # first, and the honest question is only ever "is this root admitted".
    create table(:mdl_issuing_authorities, primary_key: false) do
      add :id, :binary_id, primary_key: true
      add :certificate, :text, null: false

      # Denormalised from the certificate for listing and for the subject
      # agreement check, which runs on every document signer registered under
      # this root.
      add :subject_country, :string, null: false
      add :subject_state, :string
      add :subject_common_name, :string, null: false
      add :not_before, :utc_datetime, null: false
      add :not_after, :utc_datetime, null: false

      # SHA-256 of the DER. Two uploads of one root are the same anchor, and
      # letting both exist would mean revoking one and still trusting the other.
      add :fingerprint, :binary, null: false

      add :admitted_by_user_id, references(:users, type: :binary_id, on_delete: :nilify_all)
      add :admitted_at, :utc_datetime, null: false

      timestamps(type: :utc_datetime)
    end

    create unique_index(:mdl_issuing_authorities, [:fingerprint])
    create index(:mdl_issuing_authorities, [:subject_country])

    alter table(:workspaces) do
      # A dedicated document signer key, separate from `signing_key_id`. ISO
      # expects the document signer to rotate on its own schedule — Annex B caps
      # its certificate at 457 days — and coupling SD-JWT issuance to that
      # cycle would mean re-certifying to keep a format that needs no
      # certificate working.
      add :mdl_signing_key_id, :string
      add :mdl_signing_public_key_x, :binary
      add :mdl_signing_public_key_y, :binary

      # The Document Signer Certificate the authority issued for that key, and
      # the root it chains to.
      add :mdl_signer_certificate, :text

      add :mdl_issuing_authority_id,
          references(:mdl_issuing_authorities, type: :binary_id, on_delete: :restrict)
    end

    create index(:workspaces, [:mdl_issuing_authority_id])

    # A certificate is meaningless without the key it certifies and the root it
    # chains to, so it may not exist without them. The converse is allowed on
    # purpose: a key with no certificate is the state a workspace sits in
    # between generating its signer and getting the request back signed, which
    # can take as long as the authority takes.
    create constraint(:workspaces, :workspaces_mdl_signer_complete_check,
             check: """
             mdl_signer_certificate IS NULL
             OR (mdl_signing_key_id IS NOT NULL
                AND mdl_signing_public_key_x IS NOT NULL
                AND mdl_signing_public_key_y IS NOT NULL
                AND mdl_issuing_authority_id IS NOT NULL)
             """
           )

    alter table(:credential_schemas) do
      # Operator-supplied when the workspace issues under someone else's
      # authority; generated by `Sovra.Mdoc.DocType` when null, which is every
      # schema that exists today.
      #
      # Naming one is no longer a trust decision. Under address-in-docType
      # trust it was — generating the string was what made `org.iso.*`
      # unsquattable. Once identity moves into the certificate subject, a
      # docType is just a document-type label, and the trust decision is the
      # issuing authority row instead.
      add :doc_type, :string

      # ISO pairs docType `org.iso.18013.5.1.mDL` with namespace
      # `org.iso.18013.5.1`; Sovra's own schemas use one string for both. Null
      # means "same as the docType", which is what every existing row means.
      add :namespace, :string
    end

    # A schema may only name its own docType if its workspace has a document
    # signer, because nothing else would let a verifier find the issuer.
    # Deliberately not a database constraint: it spans two tables, and Postgres
    # cannot express that in a CHECK. `Sovra.Issuer.CredentialSchema` enforces
    # it, and `credential_schemas_doc_type_shape_check` keeps the string itself
    # honest either way.
    create constraint(:credential_schemas, :credential_schemas_doc_type_shape_check,
             check:
               "doc_type IS NULL OR doc_type ~ '^[a-z0-9]([a-z0-9_-]*[a-z0-9])?(\\.[a-z0-9]([a-z0-9_-]*[a-z0-9])?)+$'"
           )
  end
end
